# Wall-E Gesture Mirror -- local static server (pure PowerShell, no Node.js).
# ASCII only: Windows PowerShell 5.1 reads a no-BOM file as the system ANSI
# code page, so any non-ASCII char here would corrupt parsing. Keep it ASCII.
param([int]$Port = 8080)

$ErrorActionPreference = 'Stop'
$root = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot 'public'))
$sep = [System.IO.Path]::DirectorySeparatorChar

# Device script embedded for the injection engine. Read from device/ on each
# request, so editing the .py file takes effect on page refresh. The filename
# is non-ASCII, so it is located by pattern (*.py) instead of a literal name.
$deviceDir = Join-Path $PSScriptRoot 'device'

$mime = @{
  '.html' = 'text/html; charset=utf-8'
  '.js'   = 'application/javascript; charset=utf-8'
  '.css'  = 'text/css; charset=utf-8'
  '.json' = 'application/json; charset=utf-8'
  '.bin'  = 'application/octet-stream'
  '.wasm' = 'application/wasm'
  '.png'  = 'image/png'
  '.ico'  = 'image/x-icon'
}

function Write-Response($stream, [string]$status, [string]$ctype, [byte[]]$body) {
  if ($null -eq $body) { $body = [byte[]]@() }
  $head = "HTTP/1.1 $status`r`nContent-Type: $ctype`r`nContent-Length: $($body.Length)`r`nCache-Control: no-store`r`nConnection: close`r`n`r`n"
  $hb = [System.Text.Encoding]::ASCII.GetBytes($head)
  $stream.Write($hb, 0, $hb.Length)
  if ($body.Length -gt 0) { $stream.Write($body, 0, $body.Length) }
  $stream.Flush()
}

# Free the port: stop any process already listening on it (clean restart).
try {
  $conns = Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue
  foreach ($c in $conns) {
    Stop-Process -Id $c.OwningProcess -Force -ErrorAction SilentlyContinue
  }
  if ($conns) { Start-Sleep -Milliseconds 500 }
} catch {}

try {
  $listener = [System.Net.Sockets.TcpListener]::new([System.Net.IPAddress]::Loopback, $Port)
  $listener.Start()
} catch {
  Write-Host "[ERROR] Port $Port failed to start: $($_.Exception.Message)"
  Write-Host "Press Enter to exit."
  [void](Read-Host)
  exit 1
}

$url = "http://localhost:$Port"

Write-Host ""
Write-Host "  ============================================"
Write-Host "   Wall-E Gesture Mirror - local server"
Write-Host "  ============================================"
Write-Host ""
Write-Host "   Server:  $url"
Write-Host "   Open in Microsoft Edge. Close this window to stop."
Write-Host ""

# Listener is up (connections queue), so open Edge now; fall back to default.
Start-Sleep -Milliseconds 300
try {
  Start-Process "msedge.exe" $url -ErrorAction Stop
} catch {
  try { Start-Process $url -ErrorAction Stop } catch {}
}

while ($true) {
  $client = $listener.AcceptTcpClient()
  try {
    $stream = $client.GetStream()
    # 2s read timeout so a browser preconnect that sends nothing does not
    # block later requests (this is a single-threaded server).
    $stream.ReadTimeout = 2000

    # Read only the request line (e.g. "GET /path HTTP/1.1").
    $sb = [System.Text.StringBuilder]::new()
    while ($true) {
      $b = $stream.ReadByte()
      if ($b -lt 0) { break }
      if ($b -eq 10) { break }              # LF ends the line
      if ($b -ne 13) { [void]$sb.Append([char]$b) }  # skip CR
    }
    $line = $sb.ToString()
    $parts = $line -split ' '
    $rawUrl = if ($parts.Length -ge 2) { $parts[1] } else { '/' }

    # Strip query string and URL-decode.
    $pathOnly = ($rawUrl -split '\?')[0]
    $decoded = [System.Uri]::UnescapeDataString($pathOnly)

    if ($decoded -eq '/health') {
      Write-Response $stream '200 OK' 'application/json; charset=utf-8' ([System.Text.Encoding]::UTF8.GetBytes('{"ok":true,"service":"wall-e-gesture-mirror"}'))
      continue
    }

    # Dynamically generate firmware.js (window.FIRMWARE_FILES) embedding the
    # device script, so the injection engine needs no fetch of .py files.
    if ($decoded -eq '/firmware.js') {
      try {
        $fwBytes = $null
        $py = Get-ChildItem -LiteralPath $deviceDir -Filter '*.py' -File | Select-Object -First 1
        if ($null -eq $py) { throw 'no .py found under device/' }
        # UTF-8 without BOM so the browser parses it as plain JS.
        # ConvertTo-Json escapes non-ASCII to \uXXXX, which is valid JS.
        $src = [System.IO.File]::ReadAllText($py.FullName, [System.Text.Encoding]::UTF8)
        $json = (@{ $py.Name = $src } | ConvertTo-Json -Compress)
        $body = "// auto-generated by server.ps1`nwindow.FIRMWARE_FILES = $json;`n"
        $fwBytes = [System.Text.Encoding]::UTF8.GetBytes($body)
        Write-Response $stream '200 OK' 'application/javascript; charset=utf-8' $fwBytes
      } catch {
        $msg = [System.Text.Encoding]::UTF8.GetBytes('firmware build failed: ' + $_.Exception.Message)
        Write-Response $stream '500 Internal Server Error' 'text/plain; charset=utf-8' $msg
      }
      continue
    }

    if ($decoded -eq '/' -or $decoded -eq '') { $decoded = '/index.html' }
    # .NET path APIs on Windows accept both / and \; GetFullPath normalizes.
    $rel = $decoded.TrimStart('/')
    $full = [System.IO.Path]::GetFullPath((Join-Path $root $rel))

    # Directory-traversal guard: resolved path must stay inside public/.
    if (-not $full.StartsWith($root + $sep, [System.StringComparison]::OrdinalIgnoreCase) -and $full -ne $root) {
      Write-Response $stream '403 Forbidden' 'text/plain; charset=utf-8' ([System.Text.Encoding]::UTF8.GetBytes('Forbidden'))
      continue
    }
    if (-not (Test-Path -LiteralPath $full -PathType Leaf)) {
      Write-Response $stream '404 Not Found' 'text/plain; charset=utf-8' ([System.Text.Encoding]::UTF8.GetBytes('Not Found'))
      continue
    }

    $ext = [System.IO.Path]::GetExtension($full).ToLower()
    $ctype = if ($mime.ContainsKey($ext)) { $mime[$ext] } else { 'application/octet-stream' }
    $bytes = [System.IO.File]::ReadAllBytes($full)
    Write-Response $stream '200 OK' $ctype $bytes
  } catch {
    # A single bad connection must not kill the server.
  } finally {
    $client.Close()
  }
}
